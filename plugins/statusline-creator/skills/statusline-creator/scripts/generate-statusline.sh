#!/usr/bin/env bash
# Generate a Claude Code statusline script from selected items
# Usage: generate-statusline.sh [--items ITEMS] [--output PATH] [--lines N] [--install] [--help]
set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SKILL_DIR="$(dirname "$SCRIPT_DIR")"

usage() {
  cat <<'USAGE'
Generate a Claude Code statusline script from selected items.

Usage:
  generate-statusline.sh --items "model,context-bar,git,cost" [OPTIONS]

Options:
  --items ITEMS     Comma-separated list of items to include (see Available Items)
  --output PATH     Output script path (default: ~/.claude/statusline-command.sh)
  --lines N         Number of statusline rows: 1, 2, or 3 (default: 2)
  --install         Also update ~/.claude/settings.json with statusLine config
  --list            List all available items with descriptions
  --help            Show this help

Available Items:
  model             Model display name (e.g., "Opus")
  model-full        Model with 1M context indicator
  dir               Working directory (basename)
  context-bar       Visual progress bar with color thresholds
  context-pct       Context percentage (number only)
  cost              Session cost in USD
  cost-color        Cost with color thresholds ($1/$5)
  duration          Session wall-clock time (Xm Ys)
  api-duration      API response time only
  lines-changed     Lines added/removed (+N -M)
  git               Branch + staged/modified counts (cached)
  git-sync          Upstream ahead/behind indicator
  git-link          Clickable repo link (OSC 8, iTerm2/Kitty)
  worktree          Worktree name indicator
  vim-mode          Vim mode indicator ([N]/[I])
  agent             Agent name indicator
  session-id        Short session ID (8 chars)
  tokens            Detailed token counts (input/output in K)
  warn-200k         Warning when exceeds 200K tokens
  style             Output style name

Examples:
  # Standard 2-line statusline
  generate-statusline.sh --items "model,dir,git,context-bar,cost,duration" --lines 2

  # Minimal 1-line
  generate-statusline.sh --items "model,context-pct,cost" --lines 1

  # Full 3-line with git link
  generate-statusline.sh --items "model-full,dir,git,git-sync,worktree,context-bar,cost-color,duration,lines-changed" --lines 3

  # Install directly
  generate-statusline.sh --items "model,dir,git,context-bar,cost" --install
USAGE
  exit 0
}

list_items() {
  cat <<'LIST'
Available statusline items:

  DISPLAY
  ─────────────────────────────────────────────
  model           Model display name ("Opus")
  model-full      Model + 1M context indicator
  dir             Working directory basename
  session-id      Short session ID (8 chars)
  style           Output style name
  vim-mode        Vim mode ([N]/[I])
  agent           Agent name indicator
  worktree        Worktree name indicator

  CONTEXT
  ─────────────────────────────────────────────
  context-bar     Progress bar ████░░░░ with color
  context-pct     Percentage number only
  tokens          Detailed token counts (K)
  warn-200k       Warning when >200K tokens

  COST & TIME
  ─────────────────────────────────────────────
  cost            Session cost ($X.XX)
  cost-color      Cost with color thresholds
  duration        Wall-clock time (Xm Ys)
  api-duration    API response time only
  lines-changed   Lines +added -removed

  GIT
  ─────────────────────────────────────────────
  git             Branch + staged/modified (cached)
  git-sync        Upstream ahead/behind arrows
  git-link        Clickable OSC 8 repo link
LIST
  exit 0
}

# Defaults
ITEMS=""
OUTPUT="$HOME/.claude/statusline-command.sh"
LINES=2
INSTALL=false

while [ $# -gt 0 ]; do
  case "$1" in
    --items) ITEMS="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    --lines) LINES="$2"; shift 2 ;;
    --install) INSTALL=true; shift ;;
    --list) list_items ;;
    --help|-h) usage ;;
    *) echo "Unknown option: $1"; usage ;;
  esac
done

if [ -z "$ITEMS" ]; then
  echo "Error: --items is required. Use --list to see available items."
  echo "Example: generate-statusline.sh --items 'model,dir,git,context-bar,cost'"
  exit 1
fi

# Parse items into array
IFS=',' read -ra ITEM_LIST <<< "$ITEMS"

# Check which item categories are needed
needs_git=false
needs_git_cache=false
needs_cost=false
needs_context=false

for item in "${ITEM_LIST[@]}"; do
  item=$(echo "$item" | tr -d ' ')
  case "$item" in
    git|git-sync|git-link) needs_git=true; needs_git_cache=true ;;
    cost|cost-color|duration|api-duration|lines-changed) needs_cost=true ;;
    context-bar|context-pct|tokens|warn-200k) needs_context=true ;;
  esac
done

# Generate script
cat > "$OUTPUT" <<'HEADER'
#!/bin/bash
# Claude Code statusline — auto-generated by statusline-creator
# Regenerate: ~/.claude/skills/statusline-creator/scripts/generate-statusline.sh --help
input=$(cat)

# ─── Colors ───
R="\033[0m"
BOLD="\033[1m"
DIM="\033[2m"
RED="\033[31m"
GREEN="\033[32m"
YELLOW="\033[33m"
BLUE="\033[34m"
MAGENTA="\033[35m"
CYAN="\033[36m"

HEADER

# Add extraction blocks based on items needed
for item in "${ITEM_LIST[@]}"; do
  item=$(echo "$item" | tr -d ' ')
  case "$item" in
    model)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Model ───
MODEL=$(echo "$input" | jq -r '.model.display_name')
BLOCK
      ;;
    model-full)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Model (with 1M indicator) ───
MODEL=$(echo "$input" | jq -r '.model.display_name')
CTX_SIZE=$(echo "$input" | jq -r '.context_window.context_window_size // 200000')
[ "$CTX_SIZE" -ge 1000000 ] && MODEL="${MODEL} (1M)"
BLOCK
      ;;
    dir)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Directory ───
DIR=$(echo "$input" | jq -r '.workspace.current_dir // empty')
DIR_SHORT="${DIR##*/}"
BLOCK
      ;;
    context-bar)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Context Bar ───
PCT=$(echo "$input" | jq -r '.context_window.used_percentage // 0' | cut -d. -f1)
BAR_W=20; filled=$(( PCT * BAR_W / 100 ))
[ $filled -gt $BAR_W ] && filled=$BAR_W
empty=$(( BAR_W - filled ))
bar=""
[ $filled -gt 0 ] && bar=$(printf '█%.0s' $(seq 1 $filled))
[ $empty -gt 0 ] && bar+=$(printf '░%.0s' $(seq 1 $empty))
if [ "$PCT" -lt 50 ]; then CTX_C="$GREEN"
elif [ "$PCT" -lt 80 ]; then CTX_C="$YELLOW"
else CTX_C="$RED"; fi
BLOCK
      ;;
    context-pct)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Context Percentage ───
PCT=$(echo "$input" | jq -r '.context_window.used_percentage // 0' | cut -d. -f1)
BLOCK
      ;;
    cost)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Cost ───
COST=$(echo "$input" | jq -r '.cost.total_cost_usd // 0')
COST_FMT=$(printf '$%.2f' "$COST")
BLOCK
      ;;
    cost-color)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Cost (color-coded) ───
COST=$(echo "$input" | jq -r '.cost.total_cost_usd // 0')
COST_FMT=$(printf '$%.2f' "$COST")
COST_CENTS=$(echo "$COST" | awk '{printf "%d", $1 * 100}')
if [ "$COST_CENTS" -lt 100 ]; then COST_C="$GREEN"
elif [ "$COST_CENTS" -lt 500 ]; then COST_C="$YELLOW"
else COST_C="$RED"; fi
BLOCK
      ;;
    duration)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Duration ───
DUR_MS=$(echo "$input" | jq -r '.cost.total_duration_ms // 0')
DUR_M=$((DUR_MS / 60000)); DUR_S=$(((DUR_MS % 60000) / 1000))
BLOCK
      ;;
    api-duration)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── API Duration ───
API_MS=$(echo "$input" | jq -r '.cost.total_api_duration_ms // 0')
API_M=$((API_MS / 60000)); API_S=$(((API_MS % 60000) / 1000))
BLOCK
      ;;
    lines-changed)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Lines Changed ───
ADDED=$(echo "$input" | jq -r '.cost.total_lines_added // 0')
REMOVED=$(echo "$input" | jq -r '.cost.total_lines_removed // 0')
BLOCK
      ;;
    git)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Git (cached) ───
GIT_CACHE="/tmp/statusline-git-cache"
GIT_MAX_AGE=5
git_stale() {
  [ ! -f "$GIT_CACHE" ] || \
  [ $(($(date +%s) - $(stat -f %m "$GIT_CACHE" 2>/dev/null || stat -c %Y "$GIT_CACHE" 2>/dev/null || echo 0))) -gt $GIT_MAX_AGE ]
}
if git_stale; then
  if git rev-parse --git-dir >/dev/null 2>&1; then
    _BR=$(git branch --show-current 2>/dev/null)
    _ST=$(git diff --cached --numstat 2>/dev/null | wc -l | tr -d ' ')
    _MO=$(git diff --numstat 2>/dev/null | wc -l | tr -d ' ')
    _AH=$(git rev-list --count '@{upstream}..HEAD' 2>/dev/null || echo 0)
    _BH=$(git rev-list --count 'HEAD..@{upstream}' 2>/dev/null || echo 0)
    echo "$_BR|$_ST|$_MO|$_AH|$_BH" > "$GIT_CACHE"
  else
    echo "||||" > "$GIT_CACHE"
  fi
fi
IFS='|' read -r BRANCH STAGED MODIFIED GIT_AHEAD GIT_BEHIND < "$GIT_CACHE"
GIT_CHANGES=""
[ -n "$STAGED" ] && [ "$STAGED" -gt 0 ] && GIT_CHANGES="${GREEN}+${STAGED}${R}"
[ -n "$MODIFIED" ] && [ "$MODIFIED" -gt 0 ] && GIT_CHANGES="${GIT_CHANGES}${YELLOW}~${MODIFIED}${R}"
BLOCK
      ;;
    git-sync)
      # Only add if git wasn't already added (it includes AHEAD/BEHIND)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Git Sync ───
SYNC=""
if [ -n "${GIT_AHEAD:-}" ] && [ "${GIT_AHEAD:-0}" -gt 0 ] && [ "${GIT_BEHIND:-0}" -gt 0 ]; then
  SYNC="${RED}↑${GIT_AHEAD}↓${GIT_BEHIND}${R}"
elif [ -n "${GIT_AHEAD:-}" ] && [ "${GIT_AHEAD:-0}" -gt 0 ]; then
  SYNC="${GREEN}↑${GIT_AHEAD}${R}"
elif [ -n "${GIT_BEHIND:-}" ] && [ "${GIT_BEHIND:-0}" -gt 0 ]; then
  SYNC="${RED}↓${GIT_BEHIND}${R}"
elif [ -n "${BRANCH:-}" ]; then
  SYNC="${DIM}✓${R}"
fi
BLOCK
      ;;
    git-link)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Git Link (OSC 8) ───
REMOTE=$(git remote get-url origin 2>/dev/null | sed 's/git@github.com:/https:\/\/github.com\//' | sed 's/\.git$//')
GIT_LINK=""
if [ -n "$REMOTE" ]; then
  REPO_NAME=$(basename "$REMOTE")
  GIT_LINK=$(printf '%b' "\033]8;;${REMOTE}\a${REPO_NAME}\033]8;;\a")
fi
BLOCK
      ;;
    worktree)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Worktree ───
WT_NAME=$(echo "$input" | jq -r '.worktree.name // empty')
WORKTREE=""
[ -n "$WT_NAME" ] && WORKTREE=" ${MAGENTA}⎇ ${WT_NAME}${R}"
BLOCK
      ;;
    vim-mode)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Vim Mode ───
VIM_MODE=$(echo "$input" | jq -r '.vim.mode // empty')
VIM=""
if [ -n "$VIM_MODE" ]; then
  [ "$VIM_MODE" = "NORMAL" ] && VIM="${BLUE}[N]${R}" || VIM="${GREEN}[I]${R}"
fi
BLOCK
      ;;
    agent)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Agent ───
AGENT_NAME=$(echo "$input" | jq -r '.agent.name // empty')
AGENT=""
[ -n "$AGENT_NAME" ] && AGENT=" ${CYAN}🤖 ${AGENT_NAME}${R}"
BLOCK
      ;;
    session-id)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Session ID ───
SID=$(echo "$input" | jq -r '.session_id // ""' | cut -c1-8)
BLOCK
      ;;
    tokens)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Token Counts ───
IN_K=$(echo "$input" | jq -r '(.context_window.current_usage.input_tokens // 0) / 1000 | floor | tostring + "K"')
OUT_K=$(echo "$input" | jq -r '(.context_window.current_usage.output_tokens // 0) / 1000 | floor | tostring + "K"')
BLOCK
      ;;
    warn-200k)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── 200K Warning ───
EXCEEDS=$(echo "$input" | jq -r '.exceeds_200k_tokens // false')
WARN=""
[ "$EXCEEDS" = "true" ] && WARN=" ${RED}⚠ >200K${R}"
BLOCK
      ;;
    style)
      cat >> "$OUTPUT" <<'BLOCK'
# ─── Output Style ───
STYLE=$(echo "$input" | jq -r '.output_style.name // "default"')
BLOCK
      ;;
    *)
      echo "Warning: Unknown item '$item' — skipping" >&2
      ;;
  esac
done

# Add output section
echo "" >> "$OUTPUT"
echo '# ─── Output ───' >> "$OUTPUT"
python3 "$SCRIPT_DIR/generate-output.py" "$ITEMS" "$LINES" >> "$OUTPUT"

chmod +x "$OUTPUT"
echo "Generated: $OUTPUT"

# Install if requested
if $INSTALL; then
  SETTINGS="$HOME/.claude/settings.json"
  if [ -f "$SETTINGS" ]; then
    # Use jq to update statusLine in settings
    if command -v jq >/dev/null 2>&1; then
      TMP=$(mktemp)
      jq --arg cmd "bash $OUTPUT" '.statusLine = {"type": "command", "command": $cmd}' "$SETTINGS" > "$TMP"
      mv "$TMP" "$SETTINGS"
      echo "Updated: $SETTINGS (statusLine → bash $OUTPUT)"
    else
      echo "Warning: jq not found — add this to $SETTINGS manually:"
      echo "  \"statusLine\": { \"type\": \"command\", \"command\": \"bash $OUTPUT\" }"
    fi
  else
    echo "Warning: $SETTINGS not found"
  fi
fi

echo ""
echo "Test with:"
echo "  echo '{\"model\":{\"display_name\":\"Opus\"},\"workspace\":{\"current_dir\":\"/tmp/test\"},\"context_window\":{\"used_percentage\":42,\"context_window_size\":200000},\"cost\":{\"total_cost_usd\":0.05,\"total_duration_ms\":120000,\"total_api_duration_ms\":5000,\"total_lines_added\":50,\"total_lines_removed\":10}}' | bash $OUTPUT"
