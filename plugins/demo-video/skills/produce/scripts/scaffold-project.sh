#!/usr/bin/env bash
set -eu

usage() {
  cat <<EOF
Usage: $(basename "$0") [OPTIONS] <project-dir>

Scaffold a new Remotion product video project from scratch.

Arguments:
  project-dir           Directory to create the project in

Options:
  --name <name>         Project name (default: derived from directory name)
  --aspect <ratio>      Aspect ratio: 9:16, 16:9, or 1:1 (default: 9:16)
  --skip-install        Skip npm install
  -h, --help            Show this help

Examples:
  $(basename "$0") ~/dev/my-product-video
  $(basename "$0") ./videos/launch-reel --aspect 16:9
  $(basename "$0") /tmp/quick-demo --name "My Product Demo"

EOF
  exit 0
}

PROJECT_DIR=""
PROJECT_NAME=""
ASPECT="9:16"
SKIP_INSTALL=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) PROJECT_NAME="$2"; shift 2 ;;
    --aspect) ASPECT="$2"; shift 2 ;;
    --skip-install) SKIP_INSTALL=true; shift ;;
    -h|--help) usage ;;
    -*) echo "Unknown option: $1" >&2; exit 2 ;;
    *) PROJECT_DIR="$1"; shift ;;
  esac
done

if [[ -z "$PROJECT_DIR" ]]; then
  echo "Error: project directory is required" >&2
  usage
fi

# Derive project name from directory
if [[ -z "$PROJECT_NAME" ]]; then
  PROJECT_NAME=$(basename "$PROJECT_DIR")
fi

# Set dimensions from aspect ratio
case "$ASPECT" in
  9:16) WIDTH=1080; HEIGHT=1920 ;;
  16:9) WIDTH=1920; HEIGHT=1080 ;;
  1:1)  WIDTH=1080; HEIGHT=1080 ;;
  *) echo "Unknown aspect ratio: $ASPECT (use 9:16, 16:9, or 1:1)" >&2; exit 2 ;;
esac

echo "Scaffolding Remotion project: $PROJECT_NAME"
echo "  Directory: $PROJECT_DIR"
echo "  Aspect: $ASPECT (${WIDTH}x${HEIGHT})"
echo ""

# Check if directory exists
if [[ -d "$PROJECT_DIR" ]] && [[ -f "$PROJECT_DIR/remotion.config.ts" ]]; then
  echo "Remotion project already exists at $PROJECT_DIR"
  echo "Skipping scaffold — using existing project."
  exit 0
fi

# Create via Remotion CLI
mkdir -p "$PROJECT_DIR"
cd "$PROJECT_DIR"

# Initialize package.json
cat > package.json <<PJSON
{
  "name": "$PROJECT_NAME",
  "version": "1.0.0",
  "description": "Product video generated by product-video-creation skill",
  "private": true,
  "license": "UNLICENSED",
  "dependencies": {
    "@remotion/cli": "4.0.435",
    "@remotion/tailwind-v4": "4.0.435",
    "lucide-react": "latest",
    "react": "19.2.3",
    "react-dom": "19.2.3",
    "remotion": "4.0.435",
    "tailwindcss": "4.0.0"
  },
  "devDependencies": {
    "@remotion/eslint-config-flat": "4.0.435",
    "@types/react": "19.2.7",
    "@types/web": "0.0.166",
    "eslint": "9.19.0",
    "prettier": "3.8.1",
    "typescript": "5.9.3"
  },
  "scripts": {
    "dev": "remotion studio",
    "build": "remotion bundle",
    "render": "remotion render",
    "lint": "eslint src && tsc"
  },
  "sideEffects": ["*.css"]
}
PJSON

# remotion.config.ts
cat > remotion.config.ts <<'CONFIG'
import { Config } from "@remotion/cli/config";
import { enableTailwind } from '@remotion/tailwind-v4';

Config.setVideoImageFormat("jpeg");
Config.setOverwriteOutput(true);
Config.overrideWebpackConfig(enableTailwind);
CONFIG

# tsconfig.json
cat > tsconfig.json <<'TSCONFIG'
{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ES2022",
    "jsx": "react-jsx",
    "strict": true,
    "moduleResolution": "bundler",
    "esModuleInterop": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true,
    "noEmit": true
  },
  "include": ["src"]
}
TSCONFIG

# eslint.config.mjs
cat > eslint.config.mjs <<'ESLINT'
import { remotionFlatConfig } from "@remotion/eslint-config-flat";
export default remotionFlatConfig;
ESLINT

# Source files
mkdir -p src/scenes public/screenshots public/audio

# index.css with Google Fonts
cat > src/index.css <<'CSS'
@import "tailwindcss";
/* Add your brand fonts here, e.g.:
@import url('https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Playfair+Display:wght@400;700&family=Source+Serif+4:wght@400;600&display=swap');
*/
CSS

# index.ts
cat > src/index.ts <<'INDEX'
import { registerRoot } from "remotion";
import { RemotionRoot } from "./Root";

registerRoot(RemotionRoot);
INDEX

# Root.tsx
cat > src/Root.tsx <<ROOT
import "./index.css";
import { Composition } from "remotion";
import { MyComposition } from "./Composition";

export const RemotionRoot: React.FC = () => {
  return (
    <>
      <Composition
        id="ProductVideo"
        component={MyComposition}
        durationInFrames={900}
        fps={30}
        width={${WIDTH}}
        height={${HEIGHT}}
      />
    </>
  );
};
ROOT

# Composition.tsx (placeholder)
cat > src/Composition.tsx <<'COMP'
import { AbsoluteFill } from "remotion";

export const MyComposition: React.FC = () => {
  return (
    <AbsoluteFill className="bg-[#111827] flex items-center justify-center">
      <h1 className="text-white text-4xl" style={{ fontFamily: "Inter, sans-serif" }}>
        Product Video
      </h1>
    </AbsoluteFill>
  );
};
COMP

# Install dependencies
if ! $SKIP_INSTALL; then
  echo "Installing dependencies..."
  npm install 2>&1 | tail -3
fi

echo ""
echo "✓ Project scaffolded at $PROJECT_DIR"
echo ""
echo "Next steps:"
echo "  cd $PROJECT_DIR"
echo "  npm run dev          # Start Remotion studio"
echo ""
